<?php

// Feature: polyglot-architecture-upgrade, Property 10: active_traders Consistency with Database
// Validates: Requirements 3.7
//
// After ReconcileGeoCache runs, for all stalls:
//   is_open = true  → member of active_traders
//   is_open = false → absent from active_traders

use App\Console\Commands\ReconcileGeoCache;
use App\Models\Market;
use App\Models\Stall;
use App\Models\Trader;
use App\Models\User;
use App\Services\GeoService;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Artisan;
use Illuminate\Support\Facades\Redis;

uses(RefreshDatabase::class);

beforeEach(function () {
    Redis::flushdb();
});

it('guarantees active_traders is consistent with database is_open state after reconciliation across 30 randomized cases', function (
    array $openStallIds,
    array $closedStallIds,
) {
    $market = Market::create([
        'name'      => 'Reconcile Test Market',
        'location'  => 'Test',
        'county'    => 'Kisumu',
        'estate'    => 'Kolenyo',
        'is_active' => true,
    ]);

    $createdStalls = [];

    foreach ($openStallIds as $idx => $stallId) {
        $user = User::factory()->create(['role' => 'trader']);
        $stall = Stall::create([
            'market_id'    => $market->id,
            'stall_number' => 'OP'.$idx,
            'zone'         => 'A',
            'status'       => 'occupied',
            'monthly_fee'  => 1000,
            'location'     => json_encode(['lat' => -0.0917, 'lon' => 34.7679]),
        ]);
        Trader::create([
            'user_id'       => $user->id,
            'stall_id'      => $stall->id,
            'market_id'     => $market->id,
            'business_name' => 'Open Trader '.$idx,
            'is_open'       => true,
        ]);
        $createdStalls['open'][] = $stall->id;
    }

    foreach ($closedStallIds as $idx => $stallId) {
        $user = User::factory()->create(['role' => 'trader']);
        $stall = Stall::create([
            'market_id'    => $market->id,
            'stall_number' => 'CL'.$idx,
            'zone'         => 'B',
            'status'       => 'occupied',
            'monthly_fee'  => 1000,
            'location'     => json_encode(['lat' => -0.0920, 'lon' => 34.7682]),
        ]);
        Trader::create([
            'user_id'       => $user->id,
            'stall_id'      => $stall->id,
            'market_id'     => $market->id,
            'business_name' => 'Closed Trader '.$idx,
            'is_open'       => false,
        ]);
        $createdStalls['closed'][] = $stall->id;
    }

    // Pre-contaminate Redis with a stale entry to verify it gets cleaned
    Redis::geoadd(GeoService::ACTIVE_TRADERS, 34.9999, -0.9999, 'stale-999999');

    // Run reconciliation
    Artisan::call('geo:reconcile');

    $members = Redis::zrange(GeoService::ACTIVE_TRADERS, 0, -1);

    // All open stalls must be present
    foreach ($createdStalls['open'] ?? [] as $stallId) {
        expect($members)->toContain(
            (string) $stallId,
            "Open stall {$stallId} must be in active_traders after reconciliation"
        );
    }

    // All closed stalls must be absent
    foreach ($createdStalls['closed'] ?? [] as $stallId) {
        expect($members)->not->toContain(
            (string) $stallId,
            "Closed stall {$stallId} must not be in active_traders after reconciliation"
        );
    }

    // Stale entry must be removed
    expect($members)->not->toContain('stale-999999', 'Stale GEO member must be removed by reconciliation');
})->with(function () {
    $cases = [];
    for ($i = 0; $i < 30; $i++) {
        $openCount   = rand(1, 4);
        $closedCount = rand(0, 4);
        $cases[] = [
            array_fill(0, $openCount, null),    // openStallIds (count matters, IDs generated by factory)
            array_fill(0, $closedCount, null),  // closedStallIds
        ];
    }
    return $cases;
});
